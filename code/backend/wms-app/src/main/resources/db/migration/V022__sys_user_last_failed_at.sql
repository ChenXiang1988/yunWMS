-- 登录失败计数的时间窗起点
--
-- 规格「同一主体在 30 分钟内连续 5 次输入错误密码」需要一个「上一轮是从什么时候开始的」事实：
-- 只靠 failed_attempts 无法区分「窗口内错 3 次」与「上周错 1 次、今天错 2 次」，
-- 后者按规格不该被累加，旧实现却会把它累加到 3。
--
-- 可空且无默认值：为空表示还没有失败记录，判定时按「首次失败」处理。
-- 已有的失败计数不回填时间：历史值没有可信的发生时间，回填成 now() 反而会把陈年计数当成窗口内的失败。

ALTER TABLE sys_user ADD COLUMN last_failed_at timestamptz;

COMMENT ON COLUMN sys_user.last_failed_at IS '最近一次密码失败时间，30 分钟计数窗口的起点；成功登录或锁定过期后清空';
