package com.yunwms.master.domain.port;

/**
 * 货主编码取号：按编码规则生成一个全局唯一、生成后不可修改的编码，形如 {@code OWNER0001}。
 *
 * <p><b>为什么本模块自己声明取号端口，而不是直接用平台已有的取号引擎：</b>取号能力当前落在
 * {@code wms-auth}，而架构约束是 {@code auth} 与 {@code master} 互不引用（见 {@code docs/coding-project.md}
 * 第二节与 {@code ModuleBoundaryTest}）。跨模块协作只有两条正路——由上层装配，或由能力提供方暴露接口——
 * 本端口取前者：{@code wms-app} 用两个模块都在场的那份 classpath 把本端口接到取号引擎上。
 * 因此这里<b>不出现另一个模块的类型</b>。把取号引擎整体搬进本模块也是错的方向：编码规则服务的是
 * 全库所有业务对象，属于平台能力，不是货主的私有规则。
 *
 * <p><b>契约：取到的号不会再发出。</b>即使外层业务事务随后回滚，该编码也已作废，
 * 不会被第二个请求拿到。调用方因此不需要「回滚后重试取号」，也必须不要假设号段连续：
 * 浪费一个号只让号段少一格，重号则无法事后修复——编码一旦打印在标签与单据上就收不回来。
 *
 * <p>实现必须保证并发的多次调用互不相同，且调用方不得自行「先读当前值再算」。
 */
public interface OwnerCodeGenerator {

    /**
     * 取下一个货主编码。
     *
     * @return 拼接好的编码，形如 {@code OWNER0001}
     * @throws RuntimeException 取号失败（规则未配置、流水位数用尽）。具体类型由实现决定：
     *                          本模块不复制上游的异常类型，失败原因原样上抛，由用例层决定如何呈现
     */
    String next();
}
