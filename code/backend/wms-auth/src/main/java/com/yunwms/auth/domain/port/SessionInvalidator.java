package com.yunwms.auth.domain.port;

/**
 * 使会话失效的入口。
 *
 * <p>规格要求「管理员主动使指定会话失效」。踢人不是它唯一的用法：改密成功后必须让其他设备手里的旧令牌
 * 立刻作废，否则改密只挡住了下一次登录，已经登录的终端可以带着旧令牌一直用下去。两处要的是同一套动作，
 * 因此按能力定义端口，而不是按「踢人」这个入口定义。
 *
 * <p>端口只出现用户标识与「当前会话」这一相对概念，不出现令牌值与任何会话实现类型：换一种会话载体时
 * 调用方不必跟着改，单测也不必起容器。
 *
 * <p>本端口不负责判定「谁有权让别人的会话失效」——授权属于权限点，在获得授权之前不得把本能力
 * 直接暴露成管理端接口，否则任何登录用户都能踢掉任意账号。
 */
public interface SessionInvalidator {

    /**
     * 使该用户的全部会话失效。
     *
     * <p>口令被人掌握又改不回来时，这是唯一能立刻止血的动作，因此会话里的业务属性（主体类型、货主归属、
     * 待改密标记）也随会话一起被丢弃：留着它们，下一次请求会读到一个已经没有令牌支撑的身份。
     *
     * @param userId 用户标识
     */
    void invalidateAllOf(long userId);

    /**
     * 使该用户的其他会话失效，保留当前请求所用的会话。
     *
     * <p>改密成功后用它：发起改密的这台设备要继续用，其他设备必须重新登录。
     *
     * <p>调用方必须传当前会话的用户标识。传成别人的标识时，「当前会话」不在被失效的集合里，
     * 效果退化为 {@link #invalidateAllOf(long)}——那不是错误，但也不是本方法想表达的意思。
     *
     * @param userId 用户标识，必须是当前会话的登录用户
     */
    void invalidateOthersOfCurrent(long userId);
}
